package com.insightgiver.entry;

import java.time.OffsetDateTime;
import java.util.UUID;

import com.insightgiver.account.AuthenticatedAccount;

import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import org.springframework.http.HttpStatus;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/v1/entries")
class EntryController {

    /**
     * @param clientId  id generated by the app; resending the same one never creates a second entry
     * @param writtenAt when the user wrote it, which can be long before the app got to sync it
     */
    record CreateEntryRequest(
            @NotBlank @Size(max = 64) String clientId,
            @NotBlank @Size(max = 10_000) String content,
            @NotNull OffsetDateTime writtenAt) {
    }

    record EntryResponse(UUID id, String clientId, EntryStatus status) {
    }

    private final EntryService entries;

    EntryController(EntryService entries) {
        this.entries = entries;
    }

    /** Returns as soon as the entry is stored; embedding happens in the background. */
    @PostMapping
    @ResponseStatus(HttpStatus.ACCEPTED)
    EntryResponse create(@AuthenticationPrincipal AuthenticatedAccount account,
            @Valid @RequestBody CreateEntryRequest request) {
        EntryService.Accepted accepted = entries.accept(account.id(), request.clientId(), request.content(),
                request.writtenAt());
        return new EntryResponse(accepted.id(), request.clientId(), accepted.status());
    }
}
